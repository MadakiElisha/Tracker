#!/usr/bin/env python3
"""Generate sim/worlds/highway_world.sdf: a 2 km straight, 4-lane road for high-speed pursuit tests.

    python3 sim/make_highway_world.py [--drone iris_with_ardupilot|fast_quad_with_ardupilot]

The world is still called `tracker_world`, so launch_sim.sh, the camera topic and the movers keep working.
Layout (metres): road along +x from -50 to 2050, y -7..+7 (4 lanes of 3.5), shoulders to y +-10, drone spawns
at the origin facing +x. Targets `highway_car` (lane y=-1.75) and `highway_runner` (shoulder y=+8.5) start
20 m ahead and are moved by sim/move_highway.py.
"""
import argparse
import os

ROAD_X0, ROAD_X1 = -50.0, 2050.0
FUEL = "https://fuel.gazebosim.org/1.0/OpenRobotics/models/"


def box_model(name, pose, size, rgb, collide=False):
    sx, sy, sz = size
    col = (f"<collision name='c'><geometry><box><size>{sx} {sy} {sz}</size></box></geometry></collision>"
           if collide else "")
    r, g, b = rgb
    return (f"    <model name='{name}'><static>true</static><pose>{pose}</pose><link name='l'>{col}"
            f"<visual name='v'><geometry><box><size>{sx} {sy} {sz}</size></box></geometry>"
            f"<material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse></material></visual>"
            f"</link></model>\n")


def visuals_model(name, items):
    """One static model with many box visuals (far cheaper than one model per box)."""
    v = []
    for i, (pose, size, (r, g, b)) in enumerate(items):
        sx, sy, sz = size
        v.append(f"<visual name='v{i}'><pose>{pose}</pose><geometry><box><size>{sx} {sy} {sz}</size></box></geometry>"
                 f"<material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse></material></visual>")
    return f"    <model name='{name}'><static>true</static><link name='l'>{''.join(v)}</link></model>\n"


def build(drone: str) -> str:
    length = ROAD_X1 - ROAD_X0
    cx = (ROAD_X0 + ROAD_X1) / 2
    out = []
    out.append(HEADER)
    # ground (grass) and asphalt
    out.append(box_model("ground", f"{cx} 0 -0.05 0 0 0", (length + 400, 600, 0.1), (0.35, 0.5, 0.25), collide=True))
    out.append(box_model("asphalt", f"{cx} 0 0.005 0 0 0", (length, 14, 0.01), (0.18, 0.18, 0.2)))
    out.append(box_model("shoulder_left", f"{cx} 8.5 0.004 0 0 0", (length, 3, 0.01), (0.3, 0.3, 0.32)))
    out.append(box_model("shoulder_right", f"{cx} -8.5 0.004 0 0 0", (length, 3, 0.01), (0.3, 0.3, 0.32)))
    # edge lines and centre line (solid), lane lines (dashed, one box per 6 m every 12 m)
    for y, rgb, nm in ((6.9, (0.9, 0.9, 0.9), "edge_l"), (-6.9, (0.9, 0.9, 0.9), "edge_r"), (0.0, (0.9, 0.75, 0.1), "centre")):
        out.append(box_model(nm, f"{cx} {y} 0.012 0 0 0", (length, 0.15, 0.002), rgb))
    white = (0.9, 0.9, 0.9)
    dashes = [(f"{x} {y} 0.012 0 0 0", (6.0, 0.12, 0.002), white)
              for y in (-3.5, 3.5) for x in [ROAD_X0 + 6 + 12.0 * k for k in range(int(length // 12.0))]]
    out.append(visuals_model("lane_dashes", dashes))
    # distance posts every 100 m and guard rails
    posts = [(f"{x} 10.6 0.6 0 0 0", (0.2, 0.2, 1.2), (0.9, 0.5, 0.1)) for x in range(0, 2001, 100)]
    out.append(visuals_model("km_posts", posts))
    out.append(box_model("rail_l", f"{cx} 11.2 0.4 0 0 0", (length, 0.15, 0.5), (0.6, 0.6, 0.65), collide=True))
    out.append(box_model("rail_r", f"{cx} -11.2 0.4 0 0 0", (length, 0.15, 0.5), (0.6, 0.6, 0.65), collide=True))
    # roadside trees
    for i, x in enumerate(range(40, 2001, 80)):
        side = 1 if i % 2 == 0 else -1
        out.append(f"    <include><uri>{FUEL}Oak%20tree</uri><name>hwy_tree_{i}</name><static>true</static>"
                   f"<pose>{x} {side * (16 + (i % 3) * 4)} 0 0 0 0</pose></include>\n")
    # targets (moved by sim/move_highway.py)
    out.append(f"    <include><uri>{FUEL}Pickup</uri><name>highway_car</name><static>true</static>"
               f"<pose>20 -1.75 0 0 0 0</pose></include>\n")
    out.append(f"    <include><uri>{FUEL}Walking%20person</uri><name>highway_runner</name><static>true</static>"
               f"<pose>20 8.5 0 0 0 0</pose></include>\n")
    # background traffic parked on the shoulder (never moved)
    for i, x in enumerate((300, 700, 1100, 1500)):
        out.append(f"    <include><uri>{FUEL}SUV</uri><name>hwy_parked_{i}</name><static>true</static>"
                   f"<pose>{x} -8.5 0 0 0 0</pose></include>\n")
    out.append(f"    <include>\n      <uri>model://{drone}</uri>\n      <pose>0 0 0.195 0 0 0</pose>\n    </include>\n")
    out.append("  </world>\n</sdf>\n")
    return "".join(out)


HEADER = """<?xml version="1.0" ?>
<!-- GENERATED by sim/make_highway_world.py: edit the generator, not this file. -->
<sdf version="1.9">
  <world name="tracker_world">

    <physics name="1ms" type="ignore">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>

    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-air-pressure-system" name="gz::sim::systems::AirPressure"/>
    <plugin filename="gz-sim-magnetometer-system" name="gz::sim::systems::Magnetometer"/>

    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.8 0.8 0.8 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.1 -0.9</direction>
    </light>

"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--drone", default="iris_with_ardupilot", help="model to spawn (default: stock Iris)")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "worlds", "highway_world.sdf"))
    a = ap.parse_args()
    with open(a.out, "w") as f:
        f.write(build(a.drone))
    print(f"wrote {a.out} (drone: {a.drone})")


if __name__ == "__main__":
    main()
